# Clean workspace to start fresh
print("Cleaning workspace...")
for item in os.listdir('.'):
    if item not in ['.config', 'sample_data']:
        if os.path.isdir(item):
            shutil.rmtree(item)
        else:
            os.remove(item)

# Download and extract GTSRB dataset
print("Downloading dataset...")
url = 'https://storage.googleapis.com/download.tensorflow.org/data/certificate/germantrafficsigns.zip'
zip_path = 'germantrafficsigns.zip'
urllib.request.urlretrieve(url, zip_path)

with zipfile.ZipFile(zip_path, 'r') as zip_ref:
    zip_ref.extractall('GTSRB_data')

print("Dataset successfully extracted!")

# Load and preprocess images with a larger resolution (64x64)
data_dir = 'GTSRB_data/shortcuts' if os.path.exists('GTSRB_data/shortcuts') else 'GTSRB_data'
train_dir = os.path.join(data_dir, 'train')
test_dir = os.path.join(data_dir, 'validation')

def load_split_data(folder_path, img_size=(64, 64)):
    images = []
    labels = []
    for label_folder in sorted(os.listdir(folder_path)):
        class_path = os.path.join(folder_path, label_folder)
        if os.path.isdir(class_path):
            class_id = int(label_folder)
            for img_name in os.listdir(class_path):
                img_path = os.path.join(class_path, img_name)
                img = cv2.imread(img_path)
                if img is not None:
                    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
                    img = cv2.resize(img, img_size)
                    images.append(img)
                    labels.append(class_id)
    return np.array(images, dtype=np.float32) / 255.0, np.array(labels, dtype=np.int32)

print("Loading split data with higher resolution (64x64)... ")
X_train_raw, y_train_raw = load_split_data(train_dir)
X_test, y_test_raw = load_split_data(test_dir)

num_classes = len(np.unique(y_train_raw))
y_train_cat = to_categorical(y_train_raw, num_classes=num_classes)
y_test = to_categorical(y_test_raw, num_classes=num_classes)

# Stratified Validation Split
X_train, X_val, y_train, y_val = train_test_split(
    X_train_raw, y_train_cat, test_size=0.15, random_state=42, stratify=y_train_raw
)

print(f"New Train size: {X_train.shape}, Val size: {X_val.shape}, Test size: {X_test.shape}")

def build_robust_cnn(input_shape=(64, 64, 3), num_classes=43):
    model = models.Sequential([
        layers.Input(shape=input_shape),
        layers.Conv2D(32, (3, 3), activation='relu', padding='same'),
        layers.Conv2D(32, (3, 3), activation='relu'),
        layers.MaxPooling2D(pool_size=(2, 2)),
        layers.Dropout(0.25),

        layers.Conv2D(64, (3, 3), activation='relu', padding='same'),
        layers.Conv2D(64, (3, 3), activation='relu'),
        layers.MaxPooling2D(pool_size=(2, 2)),
        layers.Dropout(0.25),

        layers.Conv2D(128, (3, 3), activation='relu', padding='same'),
        layers.MaxPooling2D(pool_size=(2, 2)),
        layers.Dropout(0.3),

        layers.Flatten(),
        layers.Dense(512, activation='relu'),
        layers.Dropout(0.5),
        layers.Dense(num_classes, activation='softmax')
    ])
    return model

# Instantiate the model with the 64x64 input dimension
model = build_robust_cnn(input_shape=(64, 64, 3), num_classes=num_classes)
model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001), loss='categorical_crossentropy', metrics=['accuracy'])
model.summary()

# Train Model with proper data augmentation scaling for 64x64 resolution
train_datagen = ImageDataGenerator(
    rotation_range=10,
    zoom_range=0.1,
    width_shift_range=0.1,
    height_shift_range=0.1,
    fill_mode='nearest'
)
train_datagen.fit(X_train)

checkpoint_cb = callbacks.ModelCheckpoint('traffic_sign_model.keras', save_best_only=True, monitor='val_accuracy', mode='max')
early_stopping_cb = callbacks.EarlyStopping(monitor='val_loss', patience=3, restore_best_weights=True)
reduce_lr_cb = callbacks.ReduceLROnPlateau(monitor='val_loss', factor=0.5, patience=2, min_lr=1e-5)

print("Training CNN Model...")
history = model.fit(
    train_datagen.flow(X_train, y_train, batch_size=64),
    validation_data=(X_val, y_val),
    epochs=5,
    callbacks=[checkpoint_cb, early_stopping_cb, reduce_lr_cb]
)

# Evaluate performance and explicitly save model
test_loss, test_acc = model.evaluate(X_test, y_test, verbose=0)
print(f"Test Accuracy: {test_acc*100:.2f}%")

# Explicitly save the trained model
model.save('traffic_sign_model.keras')
print("Model saved to traffic_sign_model.keras!")

