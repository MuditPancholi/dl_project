from google.colab import files
import io
from PIL import Image
import numpy as np
import cv2
import matplotlib.pyplot as plt
import tensorflow as tf

# Ensure the best trained model is loaded
trained_model = tf.keras.models.load_model('traffic_sign_model.keras')

# Trigger the file upload widget
uploaded = files.upload()

for filename in uploaded.keys():
    # Read image
    image_data = uploaded[filename]
    image = Image.open(io.BytesIO(image_data))

    # Convert to RGB numpy array
    img_np = np.array(image.convert('RGB'))

    # Crop to a square (center crop) to prevent sign distortion when resizing
    h, w, _ = img_np.shape
    min_dim = min(h, w)
    start_h = (h - min_dim) // 2
    start_w = (w - min_dim) // 2
    cropped_img = img_np[start_h:start_h+min_dim, start_w:start_w+min_dim]

    # Preprocess matching training: Resize to 64x64 and normalize
    resized_img = cv2.resize(cropped_img, (64, 64))
    normalized_img = resized_img.astype(np.float32) / 255.0
    input_tensor = np.expand_dims(normalized_img, axis=0)

    # Predict
    predictions = trained_model.predict(input_tensor)[0]
    predicted_class_id = np.argmax(predictions)
    confidence = predictions[predicted_class_id] * 100
    predicted_label = class_names.get(predicted_class_id, "Unknown")

    # Display original, cropped, and model input images
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    axes[0].imshow(img_np)
    axes[0].set_title("Original Uploaded Image")
    axes[0].axis('off')

    axes[1].imshow(cropped_img)
    axes[1].set_title("Centered Cropped (Square)")
    axes[1].axis('off')

    axes[2].imshow(normalized_img)
    axes[2].set_title(f"Model Input (64x64)\nPredicted: {predicted_label}\nConfidence: {confidence:.2f}%")
    axes[2].axis('off')

    plt.show()